function getLang() {
  return localStorage.getItem(LANG_KEY) || "ja";
}

function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang);
}

function t(key, vars) {
  const lang = getLang();
  let str = (I18N[lang] && I18N[lang][key]) || I18N.ja[key] || key;
  if (vars) {
    Object.keys(vars).forEach(k => {
      str = str.split(`{${k}}`).join(String(vars[k]));
    });
  }
  return str;
}

function translatedDomainName(domain, lang) {
  lang = lang || getLang();
  if (lang === "ja") return domain.nameJa;
  if (lang === "en") return domain.name;
  const override = DOMAIN_NAME_OVERRIDES[lang];
  return (override && override[domain.id]) || domain.name;
}

function applyDocumentLangDir() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.documentElement.dir = RTL_LANGS.has(lang) ? "rtl" : "ltr";
  document.title = t("pageTitle");
}

function applyI18n(root) {
  root.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-html]").forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  root.querySelectorAll("[data-i18n-attr-title]").forEach(el => {
    el.title = t(el.dataset.i18nAttrTitle);
  });
}

function populateLangSelect(selectEl) {
  selectEl.innerHTML = "";
  LANGS.forEach(l => {
    const opt = document.createElement("option");
    opt.value = l.code;
    opt.textContent = l.label;
    selectEl.appendChild(opt);
  });
  selectEl.value = getLang();
}
